import assert from 'node:assert/strict';
import { parse, validate, validateIndexed, diagnosticLocations } from '../src/lib/json/engine';
import { isRecordStream, documentPath } from '../src/lib/json/document';
import { beautifyJson, minifyJson } from '../src/lib/json/transforms';
import { documentTree, editNode, pathAtOffset, valueChild } from '../src/lib/json/views';
import { treePage } from '../src/lib/json/treePage';
import { largeTable, discoverArrays, largeGraph } from '../src/lib/json/largeViews';
import { DocumentInspector } from '../src/lib/documentInspector';
import type { JsonPath } from '../src/lib/json/views';

async function readPreviewText(source: string, path: JsonPath) {
  const inspector = new DocumentInspector();
  inspector.sync(source, 1);
  return (await inspector.query({ kind: 'preview', path })).text;
}
import { maskJson } from '../src/lib/json/privacy';
import { analyze } from '../src/lib/json/analysis';
import { advanced } from '../src/lib/json/advanced';
import { repairJson } from '../src/lib/json/repair';

const source = '{"level":30,"msg":"**ready**","id":900719925474099312345}\r\n{"level":40,"msg":"line\\nnext","token":"secret"}\r\n';
assert.equal(isRecordStream(source), true);
assert.equal(validate(source).ok, true);
assert.equal(validateIndexed(source).ok, true);
assert.equal((parse(source) as { id: { value: string } }[])[0].id.value, '900719925474099312345');
assert.deepEqual(parse('null\nfalse\n42\n"text"\n[1,2]\n'), [null, false, 42, 'text', [1, 2]]);
for (const text of ['{\n"a":1\n}', '[\n1,\n2\n]', '42\n']) assert.equal(isRecordStream(text), false);
assert.equal(validate('// comment\n{"a":1,}', { mode: 'jsonc' }).ok, true);
assert.equal(validate('{"a":1}\n// trailing comment', { mode: 'jsonc' }).ok, true);
assert.equal(validate('{"a":1}\n/* trailing\ncomment */', { mode: 'jsonc' }).ok, true);
const repaired = repairJson('{}\n{"a":1,}\n');
assert.equal(repaired.ok, true);
assert.equal(isRecordStream(repaired.source), true);
for (const text of ['{} {}', '{}\n\n{}', '{}\n{"a":}', '{}\n{"a":1,}', '{}\n{"a":"broken\ntext"}', '{}\n[1\n2]\n{}', '{}\n{"a":1\n"b":2}']) assert.equal(validate(text).ok, false, text);
const errors = diagnosticLocations('{}\n{"a":}', validate('{}\n{"a":}').diagnostics);
assert.equal(errors[0].location?.line, 2);
const root = documentTree(source, false)!;
assert.equal(root.children?.length, 2);
const second = root.children![1];
assert.equal(source.slice(second.offset, second.offset + second.length), '{"level":40,"msg":"line\\nnext","token":"secret"}');
assert.deepEqual(pathAtOffset(root, source.indexOf('line')), [1, 'msg']);
assert.deepEqual(documentPath(source, source.indexOf('line')), [1, 'msg']);
assert.equal(await readPreviewText(source, [1, 'msg']), 'line\nnext');
assert.equal(await readPreviewText('"one"\n"two"', []), null);
assert.equal(await readPreviewText('"one"\n"two"', [0]), 'one');
assert.match(beautifyJson(source).source, /900719925474099312345/);
assert.equal(isRecordStream(beautifyJson(source).source), true);
assert.equal(minifyJson(source).source.split('\n').length, 3);
assert.equal(minifyJson('  { "id": 9007199254740993 }\r\n [ 1, 2 ]\r\n').source, '{"id":9007199254740993}\r\n[1,2]\r\n');
assert.equal(minifyJson(' "first\\nline" \n 42\n true\nnull').source, '"first\\nline"\n42\ntrue\nnull');
const replacement = editNode(source, valueChild(second, 1), 'replace', '"changed"', '', '2', {});
assert.equal(await readPreviewText(replacement, [1, 'msg']), 'changed');
assert.match(replacement, /900719925474099312345/);
const deleted = editNode(source, root.children![0], 'delete', '', '', '2', {});
assert.equal((parse(deleted) as { level: number }).level, 40);
const added = editNode(source, root, 'add', '{"msg":"third"}', '', '2', {});
assert.equal(await readPreviewText(added, [2, 'msg']), 'third');
assert.equal(discoverArrays(source)[0].count, 2);
assert.equal(largeTable(source, [], 0).rows[1].cells.msg, '"line\\nnext"');
assert.equal(largeGraph(source, 3).items.some(item => JSON.stringify(item.path) === '[1,"msg"]'), true);
const rows = treePage(source, { all: true, root: true, offsets: [] }).rows;
assert.equal(rows.some(row => JSON.stringify(row.path) === '[1,"msg"]'), true);
assert.equal(await readPreviewText(maskJson(source).source, [1, 'token']), '[redacted]');
assert.equal(analyze({ kind: 'diff', source, other: replacement, jsonc: false }).total, 1);
assert.match((await advanced({ kind: 'types', source, jsonc: false, indent: '2' })).source, /level/);
const large = source.repeat(25_000);
assert.ok(large.length > 2_000_000);
const indexed = validateIndexed(large);
assert.equal(indexed.ok, true);
assert.equal(indexed.folds.length, 100_000);
assert.equal(treePage(large, { all: false, root: true, offsets: [] }, 100).rows.length, 300);
assert.equal(largeTable(large, [], 100).rows[0].index, 30_000);
console.log('Record streams: validation, offsets, lossless transforms, editing, views, preview, masking, diff and types passed.');
