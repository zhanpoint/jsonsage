import assert from 'node:assert/strict';
import { defaultShortcuts, commandDefinitions } from '../src/lib/commands';
import { readShortcuts, shortcutConflict, shortcutFromEvent, shortcutLabel, writeShortcuts } from '../src/lib/shortcuts';

const key = (code: string, modifiers: Partial<{ ctrlKey: boolean; metaKey: boolean; altKey: boolean; shiftKey: boolean }> = {}, value = code.replace(/^(Key|Digit)/, '')) => ({ code, key: value, ctrlKey: false, metaKey: false, altKey: false, shiftKey: false, ...modifiers });
assert.equal(new Set(Object.values(defaultShortcuts)).size, Object.keys(commandDefinitions).length);
assert.ok(Object.values(defaultShortcuts).every(value => value.split('+').length === 2), 'Every default needs only one modifier and one key');
assert.equal(shortcutFromEvent(key('KeyN', { altKey: true })), defaultShortcuts.newHistory);
assert.equal(shortcutFromEvent(key('KeyS', { ctrlKey: true })), defaultShortcuts.saveHistory);
assert.equal(shortcutFromEvent(key('KeyS', { metaKey: true })), defaultShortcuts.saveHistory);
assert.equal(shortcutFromEvent(key('KeyO', { ctrlKey: true })), defaultShortcuts.open);
assert.equal(shortcutFromEvent(key('KeyY', { ctrlKey: true })), defaultShortcuts.redo);
assert.equal(shortcutFromEvent(key('KeyK', { ctrlKey: true })), defaultShortcuts.palette);
assert.equal(shortcutFromEvent(key('KeyK', { metaKey: true })), defaultShortcuts.palette);
assert.equal(shortcutFromEvent(key('Digit2', { altKey: true })), defaultShortcuts.tree);
assert.equal(shortcutFromEvent(key('Digit2', { ctrlKey: true, altKey: true, shiftKey: true }, '@')), 'Mod+Alt+Shift+2');
assert.equal(shortcutFromEvent(key('KeyF', { ctrlKey: true, altKey: true }, 'а')), 'Mod+Alt+F', 'Physical shortcuts must not depend on keyboard layout');
assert.equal(shortcutFromEvent(key('KeyA')), null, 'Normal typing must remain native');
assert.equal(shortcutFromEvent(key('KeyN', { altKey: true }, 'Dead')), null, 'Accent composition must remain native');
assert.equal(shortcutFromEvent(key('ControlLeft', { ctrlKey: true }, 'Control')), null);
assert.equal(shortcutFromEvent(key('F8')), 'F8');
assert.equal(shortcutFromEvent(key('F8', { shiftKey: true })), 'Shift+F8');
assert.equal(readShortcuts(JSON.stringify({ format: 'Shift+F8' })).format, 'Shift+F8');
assert.equal(shortcutConflict(defaultShortcuts, 'format', defaultShortcuts.repair), 'repair');
assert.equal(shortcutConflict(defaultShortcuts, 'format', defaultShortcuts.format), undefined);
const customized = { ...defaultShortcuts, format: 'Mod+Alt+Shift+F', graph: 'Mod+Alt+Slash' };
assert.deepEqual(readShortcuts(JSON.stringify(customized)), customized);
assert.deepEqual(readShortcuts('{bad'), defaultShortcuts);
assert.deepEqual(readShortcuts(JSON.stringify({ format: 'A' })), defaultShortcuts);
const migrated = readShortcuts(JSON.stringify({ history: 'Mod+Alt+H', newHistory: 'Mod+Alt+N', saveHistory: 'Mod+Alt+S', tree: 'Mod+Alt+2', copyRaw: 'Mod+Alt+Shift+C', unescape: 'Mod+Alt+Shift+Q', redo: 'Mod+Shift+Z', mask: 'Mod+Alt+D' }));
assert.deepEqual(migrated, defaultShortcuts, 'Stored old defaults must upgrade rather than hide the simpler defaults');
const conflict = readShortcuts(JSON.stringify({ format: defaultShortcuts.repair, history: 'F8' }));
assert.equal(conflict.format, defaultShortcuts.repair, 'A deliberate customization wins over a new default');
assert.equal(conflict.repair, '', 'A colliding new default is unassigned rather than resetting all preferences');
assert.equal(conflict.history, 'F8', 'An unrelated customization survives migration');
assert.deepEqual(readShortcuts(writeShortcuts(conflict)), conflict);
assert.deepEqual(JSON.parse(writeShortcuts(defaultShortcuts)), { version: 2, overrides: {} }, 'Only overrides are stored, so future default changes remain visible');
assert.deepEqual(readShortcuts(writeShortcuts(customized)), customized);
const explicitOldBinding = { ...defaultShortcuts, saveHistory: 'Mod+Alt+S' };
assert.deepEqual(readShortcuts(writeShortcuts(explicitOldBinding)), explicitOldBinding, 'Versioned preferences preserve a new explicit choice of an old binding');
const duplicates = readShortcuts(JSON.stringify({ version: 2, overrides: { format: 'F8', repair: 'F8', history: 'F9', tree: 'bad' } }));
assert.equal(duplicates.format, 'F8'); assert.equal(duplicates.repair, defaultShortcuts.repair);
assert.equal(duplicates.history, 'F9'); assert.equal(duplicates.tree, defaultShortcuts.tree);
assert.equal(shortcutLabel('Mod+Alt+Enter'), 'Ctrl/⌘ + Alt + ↵');
assert.equal(shortcutLabel(''), '—');
console.log('Two-key defaults, physical keyboard layouts, rebinding, versioned migration, collision and preference recovery checks passed.');
